def lesson(lid, title, desc, theme, exercises):
    return {
        "id": lid,
        "title": title,
        "description": desc,
        "theme": theme,
        "xp": 16,
        "exercises": exercises,
    }


def mc(eid, prompt, options, answer, explanation):
    return {
        "id": eid,
        "type": "multiple_choice",
        "prompt": prompt,
        "options": options,
        "answer": answer,
        "explanation": explanation,
    }


def fb(eid, prompt, answer, explanation, acceptable=None):
    ex = {
        "id": eid,
        "type": "fill_blank",
        "prompt": prompt,
        "answer": answer,
        "explanation": explanation,
    }
    if acceptable:
        ex["acceptableAnswers"] = acceptable
    return ex


def mp(eid, prompt, pairs, explanation):
    return {
        "id": eid,
        "type": "match_pairs",
        "prompt": prompt,
        "pairs": [{"left": l, "right": r} for l, r in pairs],
        "explanation": explanation,
    }


def lac(eid, prompt, spoken, options, answer, explanation):
    return {
        "id": eid,
        "type": "listen_and_choose",
        "prompt": prompt,
        "spokenText": spoken,
        "options": options,
        "answer": answer,
        "explanation": explanation,
    }


def tw(eid, prompt, answer, bank, explanation=None):
    ex = {
        "id": eid,
        "type": "tap_words_in_order",
        "prompt": prompt,
        "answer": answer,
        "bank": bank,
    }
    if explanation:
        ex["explanation"] = explanation
    return ex


def line(speaker, text):
    return {"kind": "line", "speaker": speaker, "text": text, "spokenText": text}


def choice(speaker, prompt, options, answer):
    return {
        "kind": "choice",
        "speaker": speaker,
        "prompt": prompt,
        "options": options,
        "answer": answer,
    }


def fill_turn(speaker, prompt, before, after, answer, acceptable=None):
    t = {
        "kind": "fill",
        "speaker": speaker,
        "prompt": prompt,
        "before": before,
        "after": after,
        "answer": answer,
    }
    if acceptable:
        t["acceptableAnswers"] = acceptable
    return t


def dialogue(eid, prompt, speakers, turns):
    return {
        "id": eid,
        "type": "dialogue",
        "prompt": prompt,
        "speakers": [{"id": sid, "name": name} for sid, name in speakers],
        "turns": turns,
    }


