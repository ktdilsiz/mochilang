def main():
    with open(PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)

    review_idx = None
    for i, t in enumerate(data['topics']):
        if t['id'] == 'es-en-c1-review':
            review_idx = i
            break
    if review_idx is None:
        print("ERROR: review topic not found", file=sys.stderr)
        sys.exit(1)

    existing_ex_ids = set()
    existing_lesson_ids = set()
    existing_topic_ids = set()
    for t in data['topics']:
        existing_topic_ids.add(t['id'])
        for l in t['lessons']:
            existing_lesson_ids.add(l['id'])
            for ex in l['exercises']:
                existing_ex_ids.add(ex['id'])

    new_topics = [voseo_topic, leismo_topic, particles_topic]
    for t in new_topics:
        if t['id'] in existing_topic_ids:
            print(f"ERROR: topic id collision: {t['id']}", file=sys.stderr)
            sys.exit(1)
        for l in t['lessons']:
            if l['id'] in existing_lesson_ids:
                print(f"ERROR: lesson id collision: {l['id']}", file=sys.stderr)
                sys.exit(1)
            for ex in l['exercises']:
                if ex['id'] in existing_ex_ids:
                    print(f"ERROR: exercise id collision: {ex['id']}", file=sys.stderr)
                    sys.exit(1)

    data['topics'] = data['topics'][:review_idx] + new_topics + data['topics'][review_idx:]

    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f"OK — inserted {len(new_topics)} topics before review")
    for t in new_topics:
        n_lessons = len(t['lessons'])
        n_ex = sum(len(l['exercises']) for l in t['lessons'])
        n_dialogues = sum(1 for l in t['lessons'] for ex in l['exercises'] if ex.get('type') == 'dialogue')
        print(f"  {t['id']}: {n_lessons} lessons, {n_ex} exercises, {n_dialogues} dialogue(s)")


if __name__ == '__main__':
    main()
